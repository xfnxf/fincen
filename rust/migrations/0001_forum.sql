-- Fincen forum schema. Timestamps are epoch milliseconds and prices are integer cents.
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  pass_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'member',
  banned BIGINT NOT NULL DEFAULT 0,
  ban_reason TEXT,
  bio TEXT NOT NULL DEFAULT '',
  contact TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  last_seen BIGINT NOT NULL
, prev_visit BIGINT, email TEXT);

CREATE TABLE forums (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  is_market BIGINT NOT NULL DEFAULT 0,
  staff_only BIGINT NOT NULL DEFAULT 0,
  position BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE threads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  forum_id BIGINT NOT NULL REFERENCES forums(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  title TEXT NOT NULL,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  last_post_at BIGINT NOT NULL,
  last_post_user_id BIGINT REFERENCES users(id),
  reply_count BIGINT NOT NULL DEFAULT 0,
  views BIGINT NOT NULL DEFAULT 0,
  pinned BIGINT NOT NULL DEFAULT 0,
  locked BIGINT NOT NULL DEFAULT 0,
  deleted BIGINT NOT NULL DEFAULT 0,
  listing_type TEXT,
  handle TEXT,
  price_cents BIGINT,
  status TEXT NOT NULL DEFAULT 'open'
, bumped_at BIGINT, edited_at BIGINT, status_at BIGINT);

CREATE INDEX idx_threads_forum ON threads(forum_id, deleted, pinned, last_post_at);

CREATE INDEX idx_threads_user ON threads(user_id);

CREATE TABLE posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  thread_id BIGINT NOT NULL REFERENCES threads(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  deleted BIGINT NOT NULL DEFAULT 0
, edited_at BIGINT);

CREATE INDEX idx_posts_thread ON posts(thread_id, deleted, id);

CREATE INDEX idx_posts_user ON posts(user_id);

CREATE TABLE vouches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_id BIGINT NOT NULL REFERENCES users(id),
  to_id BIGINT NOT NULL REFERENCES users(id),
  rating BIGINT NOT NULL,
  comment TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  UNIQUE(from_id, to_id)
);

CREATE INDEX idx_vouches_to ON vouches(to_id);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_id BIGINT NOT NULL REFERENCES users(id),
  to_id BIGINT NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  read BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_messages_to ON messages(to_id, read);

CREATE INDEX idx_messages_from ON messages(from_id);

CREATE TABLE reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id BIGINT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL,
  target_id BIGINT NOT NULL,
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open',
  handled_by BIGINT REFERENCES users(id),
  created_at BIGINT NOT NULL
);

CREATE TABLE saves (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  thread_id BIGINT NOT NULL REFERENCES threads(id),
  created_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, thread_id)
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  actor_id BIGINT REFERENCES users(id),
  thread_id BIGINT,
  post_id BIGINT,
  created_at BIGINT NOT NULL,
  read BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_notifications_user ON notifications(user_id, read);

CREATE TABLE external_listings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,
  handle TEXT NOT NULL,
  price_ton DOUBLE PRECISION NOT NULL,
  url TEXT NOT NULL,
  ends_at BIGINT,
  fetched_at BIGINT NOT NULL,
  UNIQUE (source, handle)
);

CREATE TABLE broker_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  source TEXT NOT NULL,
  handle TEXT NOT NULL,
  price_ton DOUBLE PRECISION,
  budget TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'open',
  handled_by BIGINT REFERENCES users(id),
  created_at BIGINT NOT NULL
);

CREATE TABLE password_resets (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE UNIQUE INDEX users_username_folded ON users (lower(username COLLATE "C"));

CREATE UNIQUE INDEX users_email_folded ON users (lower(email COLLATE "C")) WHERE email IS NOT NULL;
