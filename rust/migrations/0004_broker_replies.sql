CREATE TABLE broker_replies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES broker_requests(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_broker_replies_request ON broker_replies(request_id, id);
ALTER TABLE notifications ADD COLUMN broker_request_id BIGINT REFERENCES broker_requests(id) ON DELETE CASCADE;
